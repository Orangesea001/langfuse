    is_app_root TINYINT(1) NOT NULL DEFAULT 0,
    bookmarked TINYINT(1) NOT NULL DEFAULT 0,
    `public` TINYINT(1) NOT NULL DEFAULT 0,
    prompt_id VARCHAR(36) NOT NULL DEFAULT '',
    prompt_name VARCHAR(255) NOT NULL DEFAULT '',
    prompt_version INT,
    model_id VARCHAR(255) NOT NULL DEFAULT '',
    provided_model_name VARCHAR(255) NOT NULL DEFAULT '',
    model_parameters VARCHAR(255) NOT NULL DEFAULT '',
    input MEDIUMTEXT,
    output MEDIUMTEXT,
    metadata JSON,
    internal_model_id VARCHAR(255) NOT NULL DEFAULT '',
    usage_details JSON,
    cost_details JSON,
    total_cost DOUBLE DEFAULT 0,
    event_ts DATETIME(3) NOT NULL,
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (span_id),
    INDEX idx_project_start (project_id, start_time),
    INDEX idx_trace (trace_id),
    INDEX idx_event_ts (event_ts)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Blob storage file log
CREATE TABLE IF NOT EXISTS blob_storage_file_log (
    project_id VARCHAR(36) NOT NULL,
    trace_id VARCHAR(36) NOT NULL,
    observation_id VARCHAR(36),
    file_name VARCHAR(255) NOT NULL,
    bucket_name VARCHAR(255) NOT NULL,
    bucket_path VARCHAR(1024) NOT NULL,
    content_type VARCHAR(255),
    file_size BIGINT,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    event_ts DATETIME(3) NOT NULL,
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (bucket_path(255)),
    INDEX idx_project (project_id),
    INDEX idx_trace (trace_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

