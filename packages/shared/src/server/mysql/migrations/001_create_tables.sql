-- MySQL tables replacing ClickHouse for Langfuse analytics store.
-- These correspond to the 8 core ClickHouse tables used by ClickhouseWriter.

-- Traces table (replaces CH traces ReplacingMergeTree)
CREATE TABLE IF NOT EXISTS traces (
    id VARCHAR(36) NOT NULL,
    timestamp DATETIME(3) NOT NULL,
    name VARCHAR(255) NOT NULL DEFAULT '',
    user_id VARCHAR(255),
    metadata JSON,
    release VARCHAR(255),
    version VARCHAR(255),
    project_id VARCHAR(36) NOT NULL,
    `public` TINYINT(1) NOT NULL DEFAULT 0,
    bookmarked TINYINT(1) NOT NULL DEFAULT 0,
    tags JSON,
    input MEDIUMTEXT,
    output MEDIUMTEXT,
    session_id VARCHAR(255),
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    event_ts DATETIME(3) NOT NULL,
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    environment VARCHAR(255) DEFAULT 'default',
    PRIMARY KEY (id),
    INDEX idx_project_timestamp (project_id, timestamp),
    INDEX idx_session (session_id),
    INDEX idx_user (user_id),
    INDEX idx_event_ts (event_ts)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Observations table (replaces CH observations ReplacingMergeTree)
CREATE TABLE IF NOT EXISTS observations (
    id VARCHAR(36) NOT NULL,
    trace_id VARCHAR(36) NOT NULL,
    type VARCHAR(50) NOT NULL DEFAULT '',
    name VARCHAR(255) NOT NULL DEFAULT '',
    start_time DATETIME(3) NOT NULL,
    end_time DATETIME(3),
    completion_start_time DATETIME(3),
    provided_model_name VARCHAR(255),
    internal_model_id VARCHAR(255),
    input MEDIUMTEXT,
    output MEDIUMTEXT,
    metadata JSON,
    tags JSON,
    version VARCHAR(255),
    release VARCHAR(255),
    project_id VARCHAR(36) NOT NULL,
    prompt_id VARCHAR(36),
    prompt_name VARCHAR(255),
    prompt_version INT,
    model_parameters JSON,
    usage_details JSON,
    cost_details JSON,
    total_cost DOUBLE DEFAULT 0,
    level VARCHAR(50) DEFAULT '',
    status_message VARCHAR(255),
    parent_observation_id VARCHAR(36),
    status VARCHAR(50) DEFAULT '',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    event_ts DATETIME(3) NOT NULL,
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    environment VARCHAR(255) DEFAULT 'default',
    PRIMARY KEY (id),
    INDEX idx_trace (trace_id),
    INDEX idx_project_start (project_id, start_time),
    INDEX idx_parent (parent_observation_id),
    INDEX idx_event_ts (event_ts)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Scores table (replaces CH scores ReplacingMergeTree)
CREATE TABLE IF NOT EXISTS scores (
    id VARCHAR(36) NOT NULL,
    timestamp DATETIME(3) NOT NULL,
    project_id VARCHAR(36) NOT NULL,
    trace_id VARCHAR(36) NOT NULL,
    observation_id VARCHAR(36),
    name VARCHAR(255) NOT NULL DEFAULT '',
    value DOUBLE NOT NULL DEFAULT 0,
    source VARCHAR(50) NOT NULL DEFAULT '',
    comment MEDIUMTEXT,
    author_user_id VARCHAR(36),
    config_id VARCHAR(36),
    data_type VARCHAR(50) NOT NULL DEFAULT '',
    string_value VARCHAR(255),
    queue_id VARCHAR(36),
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    event_ts DATETIME(3) NOT NULL,
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    INDEX idx_project_trace (project_id, trace_id),
    INDEX idx_observation (observation_id),
    INDEX idx_event_ts (event_ts)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Events full table (replaces CH events_full ReplacingMergeTree)
